CREATE TABLE IF NOT EXISTS driver_profiles (
  id INT PRIMARY KEY AUTO_INCREMENT,
  user_id INT NOT NULL UNIQUE,
  first_name VARCHAR(100) NOT NULL,
  last_name VARCHAR(100) NOT NULL,
  address TEXT NULL,
  id_card_photo MEDIUMTEXT NULL,
  selfie_photo MEDIUMTEXT NULL,
  driver_license_file MEDIUMTEXT NULL,
  driver_license_expires_at DATE NULL,
  driver_license_status ENUM('en_attente','validé','expiré','rejeté') NOT NULL DEFAULT 'en_attente',
  vehicle_registration_file MEDIUMTEXT NULL,
  vehicle_registration_expires_at DATE NULL,
  vehicle_registration_status ENUM('en_attente','validé','expiré','rejeté') NOT NULL DEFAULT 'en_attente',
  vehicle_insurance_file MEDIUMTEXT NULL,
  vehicle_insurance_expires_at DATE NULL,
  vehicle_insurance_status ENUM('en_attente','validé','expiré','rejeté') NOT NULL DEFAULT 'en_attente',
  technical_inspection_file MEDIUMTEXT NULL,
  technical_inspection_expires_at DATE NULL,
  technical_inspection_status ENUM('en_attente','validé','expiré','rejeté') NOT NULL DEFAULT 'en_attente',
  verification_status ENUM('pending','verified','rejected') NOT NULL DEFAULT 'pending',
  rejection_reason TEXT NULL,
  submitted_at DATETIME NULL,
  verified_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_driver_profiles_user
    FOREIGN KEY (user_id) REFERENCES users(id)
    ON DELETE CASCADE,
  INDEX idx_driver_profiles_status (verification_status),
  INDEX idx_driver_profiles_submitted_at (submitted_at)
);
